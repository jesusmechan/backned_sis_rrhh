CREATE OR REPLACE FUNCTION fn_usuario_puede_decidir_paso(
    p_id_paso INTEGER,
    p_id_usuario INTEGER
)
RETURNS BOOLEAN AS $$
DECLARE
    v_paso solicitud_paso_aprobacion%ROWTYPE;
    v_id_rol INTEGER;
BEGIN
    SELECT * INTO v_paso
    FROM solicitud_paso_aprobacion
    WHERE id_paso_solicitud = p_id_paso;

    IF NOT FOUND OR v_paso.estado <> 'EN_CURSO' THEN
        RETURN FALSE;
    END IF;

    SELECT id_rol INTO v_id_rol
    FROM usuario
    WHERE id_usuario = p_id_usuario
      AND activo;

    IF v_id_rol IS NULL THEN
        RETURN FALSE;
    END IF;

    IF v_paso.tipo_aprobador IN ('JEFE_INMEDIATO', 'USUARIO') THEN
        RETURN v_paso.id_usuario_asignado = p_id_usuario;
    END IF;

    RETURN v_paso.id_rol = v_id_rol;
END;
$$ LANGUAGE plpgsql STABLE;

CREATE OR REPLACE FUNCTION fn_validar_decision_paso()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.estado <> 'EN_CURSO' AND NEW.estado IN ('APROBADO', 'RECHAZADO') THEN
        RAISE EXCEPTION 'Solo se puede decidir el paso que está en curso.';
    END IF;

    IF NEW.estado IN ('APROBADO', 'RECHAZADO') THEN
        IF NEW.id_usuario_decision IS NULL THEN
            RAISE EXCEPTION 'Debe indicarse el usuario que toma la decisión.';
        END IF;
        IF NOT fn_usuario_puede_decidir_paso(NEW.id_paso_solicitud, NEW.id_usuario_decision) THEN
            RAISE EXCEPTION 'El usuario % no está autorizado para el paso %.',
                NEW.id_usuario_decision, NEW.nombre_paso;
        END IF;
        NEW.fecha_decision := COALESCE(NEW.fecha_decision, NOW());
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validar_decision_paso
    BEFORE UPDATE OF estado ON solicitud_paso_aprobacion
    FOR EACH ROW
    WHEN (OLD.estado IS DISTINCT FROM NEW.estado)
    EXECUTE FUNCTION fn_validar_decision_paso();

CREATE OR REPLACE FUNCTION fn_avanzar_flujo_aprobacion()
RETURNS TRIGGER AS $$
DECLARE
    v_siguiente INTEGER;
    v_accion accion_solicitud;
    v_estado_final estado_solicitud;
BEGIN
    v_accion := CASE NEW.estado
        WHEN 'APROBADO' THEN 'APROBAR'::accion_solicitud
        ELSE 'RECHAZAR'::accion_solicitud
    END;

    INSERT INTO historial_solicitud (
        id_solicitud_permiso,
        id_solicitud_hora_extra,
        id_paso_solicitud,
        id_usuario,
        accion,
        estado_anterior,
        estado_nuevo,
        comentario
    ) VALUES (
        NEW.id_solicitud_permiso,
        NEW.id_solicitud_hora_extra,
        NEW.id_paso_solicitud,
        NEW.id_usuario_decision,
        v_accion,
        'PENDIENTE'::estado_solicitud,
        CASE
            WHEN NEW.estado = 'APROBADO' THEN 'PENDIENTE'::estado_solicitud
            ELSE 'RECHAZADO'::estado_solicitud
        END,
        NEW.comentario
    );

    IF NEW.estado = 'RECHAZADO' THEN
        UPDATE solicitud_paso_aprobacion
        SET estado = 'OMITIDO'
        WHERE estado IN ('PENDIENTE')
          AND id_paso_solicitud <> NEW.id_paso_solicitud
          AND (
              (NEW.id_solicitud_permiso IS NOT NULL AND id_solicitud_permiso = NEW.id_solicitud_permiso)
              OR (NEW.id_solicitud_hora_extra IS NOT NULL AND id_solicitud_hora_extra = NEW.id_solicitud_hora_extra)
          );

        v_estado_final := 'RECHAZADO';
    ELSE
        SELECT id_paso_solicitud INTO v_siguiente
        FROM solicitud_paso_aprobacion
        WHERE estado = 'PENDIENTE'
          AND (
              (NEW.id_solicitud_permiso IS NOT NULL AND id_solicitud_permiso = NEW.id_solicitud_permiso)
              OR (NEW.id_solicitud_hora_extra IS NOT NULL AND id_solicitud_hora_extra = NEW.id_solicitud_hora_extra)
          )
        ORDER BY numero_paso
        LIMIT 1;

        IF v_siguiente IS NOT NULL THEN
            UPDATE solicitud_paso_aprobacion
            SET estado = 'EN_CURSO',
                fecha_inicio = NOW()
            WHERE id_paso_solicitud = v_siguiente;
            RETURN NEW;
        END IF;

        v_estado_final := 'APROBADO';
    END IF;

    IF NEW.id_solicitud_permiso IS NOT NULL THEN
        UPDATE solicitud_permiso
        SET estado = v_estado_final
        WHERE id_solicitud_permiso = NEW.id_solicitud_permiso;
    ELSE
        UPDATE solicitud_hora_extra
        SET estado = v_estado_final
        WHERE id_solicitud_hora_extra = NEW.id_solicitud_hora_extra;
    END IF;

    INSERT INTO historial_solicitud (
        id_solicitud_permiso,
        id_solicitud_hora_extra,
        id_paso_solicitud,
        id_usuario,
        accion,
        estado_anterior,
        estado_nuevo,
        comentario
    ) VALUES (
        NEW.id_solicitud_permiso,
        NEW.id_solicitud_hora_extra,
        NEW.id_paso_solicitud,
        NEW.id_usuario_decision,
        v_accion,
        'PENDIENTE'::estado_solicitud,
        v_estado_final,
        NEW.comentario
    );

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_avanzar_flujo_aprobacion
    AFTER UPDATE OF estado ON solicitud_paso_aprobacion
    FOR EACH ROW
    WHEN (OLD.estado = 'EN_CURSO' AND NEW.estado IN ('APROBADO', 'RECHAZADO'))
    EXECUTE FUNCTION fn_avanzar_flujo_aprobacion();

