SELECT
    sp.id_solicitud_permiso,
    ve.codigo_empleado,
    ve.nombre_completo,
    ve.area,
    tp.nombre AS tipo_permiso,
    cfg.nombre AS flujo_aprobacion,
    sp.fecha_inicio,
    sp.fecha_fin,
    (sp.fecha_fin - sp.fecha_inicio) + 1 AS dias,
    sp.motivo,
    sp.estado,
    paso.nombre_paso AS paso_actual,
    paso.tipo_aprobador AS tipo_aprobador_actual,
    COALESCE(ua.nombre_usuario, r.nombre) AS responsable_actual,
    ult.nombre_usuario AS ultimo_decisor,
    ult.fecha_decision,
    ult.comentario AS comentario_decision,
    sp.fecha_creacion
FROM solicitud_permiso sp
JOIN v_empleado ve ON ve.id_empleado = sp.id_empleado
JOIN tipo_permiso tp ON tp.id_tipo_permiso = sp.id_tipo_permiso
LEFT JOIN configuracion_aprobacion cfg ON cfg.id_configuracion = sp.id_configuracion
LEFT JOIN solicitud_paso_aprobacion paso
    ON paso.id_solicitud_permiso = sp.id_solicitud_permiso
   AND paso.estado = 'EN_CURSO'
LEFT JOIN usuario ua ON ua.id_usuario = paso.id_usuario_asignado
LEFT JOIN rol r ON r.id_rol = paso.id_rol
LEFT JOIN LATERAL (
    SELECT u.nombre_usuario, p.fecha_decision, p.comentario
    FROM solicitud_paso_aprobacion p
    JOIN usuario u ON u.id_usuario = p.id_usuario_decision
    WHERE p.id_solicitud_permiso = sp.id_solicitud_permiso
      AND p.estado IN ('APROBADO', 'RECHAZADO')
    ORDER BY p.numero_paso DESC
    LIMIT 1
) ult ON TRUE;

