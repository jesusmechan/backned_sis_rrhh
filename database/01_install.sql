LEFT JOIN usuario ua ON ua.id_usuario = paso.id_usuario_asignado
LEFT JOIN rol r ON r.id_rol = paso.id_rol
LEFT JOIN LATERAL (
    SELECT u.nombre_usuario, p.fecha_decision, p.comentario
    FROM solicitud_paso_aprobacion p
    JOIN usuario u ON u.id_usuario = p.id_usuario_decision
    WHERE p.id_solicitud_hora_extra = he.id_solicitud_hora_extra
      AND p.estado IN ('APROBADO', 'RECHAZADO')
    ORDER BY p.numero_paso DESC
    LIMIT 1
) ult ON TRUE;

CREATE OR REPLACE VIEW v_pasos_solicitud AS
SELECT
    p.id_paso_solicitud,
    CASE
        WHEN p.id_solicitud_permiso IS NOT NULL THEN 'PERMISO'
        ELSE 'HORA_EXTRA'
    END AS tipo_solicitud,
    COALESCE(p.id_solicitud_permiso, p.id_solicitud_hora_extra) AS id_solicitud,
    p.numero_paso,
    p.nombre_paso,
    p.tipo_aprobador,
    r.nombre AS rol,
    ua.nombre_usuario AS usuario_asignado,
    p.estado,
    ud.nombre_usuario AS usuario_decision,
    p.fecha_inicio,
    p.fecha_decision,
    p.comentario
FROM solicitud_paso_aprobacion p
LEFT JOIN rol r ON r.id_rol = p.id_rol
LEFT JOIN usuario ua ON ua.id_usuario = p.id_usuario_asignado
LEFT JOIN usuario ud ON ud.id_usuario = p.id_usuario_decision;

CREATE OR REPLACE VIEW v_bandeja_aprobacion AS
SELECT
    p.id_paso_solicitud,
    p.id_usuario_asignado,
    p.id_rol,
    CASE
        WHEN p.id_solicitud_permiso IS NOT NULL THEN 'PERMISO'
        ELSE 'HORA_EXTRA'
    END AS tipo_solicitud,
    COALESCE(p.id_solicitud_permiso, p.id_solicitud_hora_extra) AS id_solicitud,
    COALESCE(ve_p.nombre_completo, ve_h.nombre_completo) AS solicitante,
    COALESCE(tp.nombre, 'Horas extras') AS tipo_tramite,
    p.numero_paso,
    p.nombre_paso,
    p.tipo_aprobador,
    p.fecha_inicio,
    COALESCE(sp.motivo, he.motivo) AS motivo
FROM solicitud_paso_aprobacion p
LEFT JOIN solicitud_permiso sp ON sp.id_solicitud_permiso = p.id_solicitud_permiso
LEFT JOIN solicitud_hora_extra he ON he.id_solicitud_hora_extra = p.id_solicitud_hora_extra
LEFT JOIN tipo_permiso tp ON tp.id_tipo_permiso = sp.id_tipo_permiso
LEFT JOIN v_empleado ve_p ON ve_p.id_empleado = sp.id_empleado
LEFT JOIN v_empleado ve_h ON ve_h.id_empleado = he.id_empleado
WHERE p.estado = 'EN_CURSO';

