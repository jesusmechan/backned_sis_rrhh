-- -----------------------------------------------------------------------------
-- Tipos enumerados
-- -----------------------------------------------------------------------------
CREATE TYPE tipo_documento AS ENUM ('DNI', 'CE', 'PASAPORTE');
CREATE TYPE sexo_empleado AS ENUM ('M', 'F');
CREATE TYPE tipo_contrato AS ENUM ('PLANILLA', 'RECIBO_HONORARIOS', 'PRACTICAS');
CREATE TYPE estado_empleado AS ENUM ('ACTIVO', 'INACTIVO', 'CESADO');
CREATE TYPE tipo_marcacion AS ENUM ('INGRESO', 'SALIDA');
CREATE TYPE estado_solicitud AS ENUM ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'CANCELADO');
CREATE TYPE accion_solicitud AS ENUM (
    'REGISTRAR',
    'ENVIAR_APROBACION',
    'APROBAR',
    'RECHAZAR',
    'CANCELAR',
    'ACTUALIZAR'
);
CREATE TYPE estado_carga AS ENUM ('PROCESANDO', 'COMPLETADA', 'COMPLETADA_CON_ERRORES', 'FALLIDA');
CREATE TYPE resultado_fila_carga AS ENUM ('INSERTADO', 'ACTUALIZADO', 'ERROR');
CREATE TYPE formato_reporte AS ENUM ('EXCEL', 'PDF');
CREATE TYPE tipo_reporte AS ENUM (
    'TRABAJADORES',
    'PERMISOS',
    'HORAS_EXTRAS',
    'ASISTENCIA',
    'USUARIOS'
);
CREATE TYPE tipo_origen_flujo AS ENUM ('PERMISO', 'HORA_EXTRA');
CREATE TYPE tipo_aprobador AS ENUM ('JEFE_INMEDIATO', 'ROL', 'USUARIO');
CREATE TYPE estado_paso_aprobacion AS ENUM (
    'PENDIENTE',
    'EN_CURSO',
    'APROBADO',
    'RECHAZADO',
    'OMITIDO',
    'CANCELADO'
);

-- -----------------------------------------------------------------------------
-- Catálogos organizacionales (SS-01)
-- -----------------------------------------------------------------------------
CREATE TABLE area (
    id_area         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(80) NOT NULL,
    descripcion     VARCHAR(250),
    activo          BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_area_nombre UNIQUE (nombre)
);

CREATE TABLE cargo (
    id_cargo        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(80) NOT NULL,
    descripcion     VARCHAR(250),
    activo          BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_cargo_nombre UNIQUE (nombre)
);

CREATE TABLE horario_laboral (
    id_horario      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(80) NOT NULL,
    hora_ingreso    TIME NOT NULL,
    hora_salida     TIME NOT NULL,
    minutos_refrigerio INTEGER NOT NULL DEFAULT 60,
    activo          BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_horario_nombre UNIQUE (nombre),
    CONSTRAINT ck_horario_rango CHECK (hora_salida > hora_ingreso),
    CONSTRAINT ck_horario_refrigerio CHECK (minutos_refrigerio BETWEEN 0 AND 180)
);

CREATE TABLE tipo_permiso (
    id_tipo_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(30) NOT NULL,
    nombre          VARCHAR(80) NOT NULL,
    requiere_sustento BOOLEAN NOT NULL DEFAULT FALSE,
    activo          BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_tipo_permiso_codigo UNIQUE (codigo),
    CONSTRAINT uq_tipo_permiso_nombre UNIQUE (nombre)
);

CREATE TABLE parametro_sistema (
    clave           VARCHAR(80) PRIMARY KEY,
    valor           VARCHAR(200) NOT NULL,
    descripcion     VARCHAR(300),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- -----------------------------------------------------------------------------
-- Usuarios, roles y permisos (SS-05, RI-05, RG-02, RG-13)
-- -----------------------------------------------------------------------------
CREATE TABLE rol (
    id_rol          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(30) NOT NULL,
    nombre          VARCHAR(80) NOT NULL,
    descripcion     VARCHAR(250),
    activo          BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_rol_codigo UNIQUE (codigo)
);

CREATE TABLE permiso_funcional (
    id_permiso      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(60) NOT NULL,
    nombre          VARCHAR(120) NOT NULL,
    modulo          VARCHAR(40) NOT NULL,
    descripcion     VARCHAR(250),
    CONSTRAINT uq_permiso_funcional_codigo UNIQUE (codigo)
);

CREATE TABLE rol_permiso (
    id_rol          INTEGER NOT NULL REFERENCES rol (id_rol) ON DELETE CASCADE,
    id_permiso      INTEGER NOT NULL REFERENCES permiso_funcional (id_permiso) ON DELETE CASCADE,
    fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (id_rol, id_permiso)
);

-- Menú dinámico por perfil (rol)
CREATE TABLE menu_item (
    id_menu         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(40) NOT NULL,
    etiqueta        VARCHAR(80) NOT NULL,
    ruta            VARCHAR(120) NOT NULL,
    icono           VARCHAR(40) NOT NULL,
    grupo           VARCHAR(40) NOT NULL,
    descripcion     VARCHAR(200),
    orden           INTEGER NOT NULL DEFAULT 0,
    activo          BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_menu_item_codigo UNIQUE (codigo)
);

CREATE TABLE menu_rol (
    id_menu INTEGER NOT NULL REFERENCES menu_item (id_menu) ON DELETE CASCADE,
    id_rol  INTEGER NOT NULL REFERENCES rol (id_rol) ON DELETE CASCADE,
    PRIMARY KEY (id_menu, id_rol)
);

-- -----------------------------------------------------------------------------
-- Personal (SS-01, RI-01, RG-03)
-- id_jefe_inmediato pertenece al organigrama, no a la solicitud.
-- El flujo lo usa cuando un paso es de tipo JEFE_INMEDIATO.
-- -----------------------------------------------------------------------------
CREATE TABLE empleado (
    id_empleado         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_empleado     VARCHAR(20) NOT NULL,
    tipo_documento      tipo_documento NOT NULL DEFAULT 'DNI',
    numero_documento    VARCHAR(20) NOT NULL,
    nombres             VARCHAR(80) NOT NULL,
    apellido_paterno    VARCHAR(80) NOT NULL,
    apellido_materno    VARCHAR(80) NOT NULL,
    fecha_nacimiento    DATE,
    sexo                sexo_empleado,
    correo_institucional VARCHAR(120) NOT NULL,
    correo_personal     VARCHAR(120),
    telefono            VARCHAR(20),
    direccion           VARCHAR(200),
    fecha_ingreso       DATE NOT NULL,
    fecha_cese          DATE,
    id_area             INTEGER NOT NULL REFERENCES area (id_area),
    id_cargo            INTEGER NOT NULL REFERENCES cargo (id_cargo),
    id_horario          INTEGER NOT NULL REFERENCES horario_laboral (id_horario),
    tipo_contrato       tipo_contrato NOT NULL DEFAULT 'PLANILLA',
    estado              estado_empleado NOT NULL DEFAULT 'ACTIVO',
    id_jefe_inmediato   INTEGER REFERENCES empleado (id_empleado),
    fecha_creacion      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_empleado_codigo UNIQUE (codigo_empleado),
    CONSTRAINT uq_empleado_documento UNIQUE (tipo_documento, numero_documento),
    CONSTRAINT uq_empleado_correo UNIQUE (correo_institucional),
    CONSTRAINT ck_empleado_cese CHECK (fecha_cese IS NULL OR fecha_cese >= fecha_ingreso),
    CONSTRAINT ck_empleado_nacimiento CHECK (fecha_nacimiento IS NULL OR fecha_nacimiento < fecha_ingreso),
    CONSTRAINT ck_empleado_dni CHECK (
        tipo_documento <> 'DNI' OR numero_documento ~ '^[0-9]{8}$'
    ),
    CONSTRAINT ck_empleado_no_autojefe CHECK (
        id_jefe_inmediato IS NULL OR id_jefe_inmediato <> id_empleado
    )
);

CREATE TABLE usuario (
    id_usuario          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado         INTEGER REFERENCES empleado (id_empleado),
    id_rol              INTEGER NOT NULL REFERENCES rol (id_rol),
    nombre_usuario      VARCHAR(60) NOT NULL,
    correo              VARCHAR(120) NOT NULL,
    password_hash       TEXT NOT NULL,
    activo              BOOLEAN NOT NULL DEFAULT TRUE,
    ultimo_acceso       TIMESTAMPTZ,
    fecha_creacion      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_usuario_nombre UNIQUE (nombre_usuario),
    CONSTRAINT uq_usuario_correo UNIQUE (correo),
    CONSTRAINT uq_usuario_empleado UNIQUE (id_empleado)
);

-- -----------------------------------------------------------------------------
-- Asistencia (SS-04, RI-04, RG-11, RC-09)
-- -----------------------------------------------------------------------------
CREATE TABLE marcacion (
    id_marcacion        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado         INTEGER NOT NULL REFERENCES empleado (id_empleado),
    tipo                tipo_marcacion NOT NULL,
    fecha_hora          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha               DATE GENERATED ALWAYS AS ((fecha_hora AT TIME ZONE 'America/Lima')::date) STORED,
    origen              VARCHAR(20) NOT NULL DEFAULT 'WEB',
    observacion         VARCHAR(250),
    id_usuario_registro INTEGER REFERENCES usuario (id_usuario),
    fecha_creacion      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_marcacion_origen CHECK (origen IN ('WEB', 'MANUAL', 'CORRECCION'))
);

-- -----------------------------------------------------------------------------
-- Configuración de aprobaciones (RG-06)
-- Un flujo por tipo de trámite. Vacaciones, salud, horas extras, etc.
-- pueden tener circuitos distintos (jefe -> RR. HH. -> gerencia).
-- -----------------------------------------------------------------------------
CREATE TABLE configuracion_aprobacion (
    id_configuracion    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(40) NOT NULL,
    nombre              VARCHAR(120) NOT NULL,
    tipo_origen         tipo_origen_flujo NOT NULL,
    id_tipo_permiso     INTEGER REFERENCES tipo_permiso (id_tipo_permiso),
    descripcion         VARCHAR(300),
    activo              BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_configuracion_codigo UNIQUE (codigo),
    CONSTRAINT ck_config_tipo_permiso CHECK (
        (tipo_origen = 'PERMISO')
        OR (tipo_origen = 'HORA_EXTRA' AND id_tipo_permiso IS NULL)
    )
);

CREATE TABLE configuracion_aprobacion_detalle (
    id_detalle          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_configuracion    INTEGER NOT NULL REFERENCES configuracion_aprobacion (id_configuracion) ON DELETE CASCADE,
    numero_paso         INTEGER NOT NULL,
    nombre_paso         VARCHAR(120) NOT NULL,
    tipo_aprobador      tipo_aprobador NOT NULL,
    id_rol              INTEGER REFERENCES rol (id_rol),
    id_usuario          INTEGER REFERENCES usuario (id_usuario),
    es_obligatorio      BOOLEAN NOT NULL DEFAULT TRUE,
    activo              BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_config_detalle_paso UNIQUE (id_configuracion, numero_paso),
    CONSTRAINT ck_config_detalle_paso CHECK (numero_paso >= 1),
    CONSTRAINT ck_config_detalle_aprobador CHECK (
        (tipo_aprobador = 'JEFE_INMEDIATO' AND id_rol IS NULL AND id_usuario IS NULL)
        OR (tipo_aprobador = 'ROL' AND id_rol IS NOT NULL AND id_usuario IS NULL)
        OR (tipo_aprobador = 'USUARIO' AND id_usuario IS NOT NULL AND id_rol IS NULL)
    )
);

CREATE UNIQUE INDEX uq_config_activa_especifica
    ON configuracion_aprobacion (tipo_origen, id_tipo_permiso)
    WHERE activo AND id_tipo_permiso IS NOT NULL;

CREATE UNIQUE INDEX uq_config_activa_generica
    ON configuracion_aprobacion (tipo_origen)
    WHERE activo AND id_tipo_permiso IS NULL;

-- -----------------------------------------------------------------------------
-- Permisos (SS-02, RI-02, RG-04)
-- Solo datos del pedido. El circuito vive en la configuración y en los pasos.
-- -----------------------------------------------------------------------------
CREATE TABLE solicitud_permiso (
    id_solicitud_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado         INTEGER NOT NULL REFERENCES empleado (id_empleado),
    id_tipo_permiso     INTEGER NOT NULL REFERENCES tipo_permiso (id_tipo_permiso),
    id_configuracion    INTEGER REFERENCES configuracion_aprobacion (id_configuracion),
    fecha_inicio        DATE NOT NULL,
    fecha_fin           DATE NOT NULL,
    hora_inicio         TIME,
    hora_fin            TIME,
    motivo              VARCHAR(400) NOT NULL,
    estado              estado_solicitud NOT NULL DEFAULT 'PENDIENTE',
    fecha_creacion      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_permiso_rango_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT ck_permiso_horas CHECK (
        (hora_inicio IS NULL AND hora_fin IS NULL)
        OR (hora_inicio IS NOT NULL AND hora_fin IS NOT NULL AND hora_fin > hora_inicio)
    ),
    CONSTRAINT ck_permiso_motivo CHECK (length(btrim(motivo)) >= 5)
);

-- -----------------------------------------------------------------------------
-- Horas extras (SS-03, RI-03, RG-05)
-- -----------------------------------------------------------------------------
CREATE TABLE solicitud_hora_extra (
    id_solicitud_hora_extra INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado         INTEGER NOT NULL REFERENCES empleado (id_empleado),
    id_configuracion    INTEGER REFERENCES configuracion_aprobacion (id_configuracion),
    fecha               DATE NOT NULL,
    hora_inicio         TIME NOT NULL,
    hora_fin            TIME NOT NULL,
    cantidad_horas      NUMERIC(5,2) NOT NULL,
    motivo              VARCHAR(400) NOT NULL,
    estado              estado_solicitud NOT NULL DEFAULT 'PENDIENTE',
    fecha_creacion      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_hora_extra_rango CHECK (hora_fin > hora_inicio),
    CONSTRAINT ck_hora_extra_cantidad CHECK (cantidad_horas > 0 AND cantidad_horas <= 8),
    CONSTRAINT ck_hora_extra_motivo CHECK (length(btrim(motivo)) >= 5)
);

-- -----------------------------------------------------------------------------
-- Pasos reales de cada solicitud (instancia del detalle configurado)
-- -----------------------------------------------------------------------------
CREATE TABLE solicitud_paso_aprobacion (
    id_paso_solicitud       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud_permiso    INTEGER REFERENCES solicitud_permiso (id_solicitud_permiso) ON DELETE CASCADE,
    id_solicitud_hora_extra INTEGER REFERENCES solicitud_hora_extra (id_solicitud_hora_extra) ON DELETE CASCADE,
    id_configuracion        INTEGER NOT NULL REFERENCES configuracion_aprobacion (id_configuracion),
    id_detalle              INTEGER NOT NULL REFERENCES configuracion_aprobacion_detalle (id_detalle),
    numero_paso             INTEGER NOT NULL,
    nombre_paso             VARCHAR(120) NOT NULL,
    tipo_aprobador          tipo_aprobador NOT NULL,
    id_rol                  INTEGER REFERENCES rol (id_rol),
    id_usuario_asignado     INTEGER REFERENCES usuario (id_usuario),
    estado                  estado_paso_aprobacion NOT NULL DEFAULT 'PENDIENTE',
    id_usuario_decision     INTEGER REFERENCES usuario (id_usuario),
    fecha_inicio            TIMESTAMPTZ,
    fecha_decision          TIMESTAMPTZ,
    comentario              VARCHAR(400),
    fecha_creacion          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_paso_una_solicitud CHECK (
        (id_solicitud_permiso IS NOT NULL AND id_solicitud_hora_extra IS NULL)
        OR (id_solicitud_permiso IS NULL AND id_solicitud_hora_extra IS NOT NULL)
    ),
    CONSTRAINT ck_paso_numero CHECK (numero_paso >= 1),
    CONSTRAINT ck_paso_decision CHECK (
        estado NOT IN ('APROBADO', 'RECHAZADO')
        OR (id_usuario_decision IS NOT NULL AND fecha_decision IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_paso_permiso_numero
    ON solicitud_paso_aprobacion (id_solicitud_permiso, numero_paso)
    WHERE id_solicitud_permiso IS NOT NULL;

CREATE UNIQUE INDEX uq_paso_hora_extra_numero
    ON solicitud_paso_aprobacion (id_solicitud_hora_extra, numero_paso)
    WHERE id_solicitud_hora_extra IS NOT NULL;

CREATE UNIQUE INDEX uq_paso_permiso_en_curso
    ON solicitud_paso_aprobacion (id_solicitud_permiso)
    WHERE id_solicitud_permiso IS NOT NULL AND estado = 'EN_CURSO';

CREATE UNIQUE INDEX uq_paso_hora_extra_en_curso
    ON solicitud_paso_aprobacion (id_solicitud_hora_extra)
    WHERE id_solicitud_hora_extra IS NOT NULL AND estado = 'EN_CURSO';

-- -----------------------------------------------------------------------------
-- Trazabilidad de solicitudes (SS-07, RI-06, RG-07, RRN-04)
-- -----------------------------------------------------------------------------
CREATE TABLE historial_solicitud (
    id_historial            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud_permiso    INTEGER REFERENCES solicitud_permiso (id_solicitud_permiso) ON DELETE CASCADE,
    id_solicitud_hora_extra INTEGER REFERENCES solicitud_hora_extra (id_solicitud_hora_extra) ON DELETE CASCADE,
    id_paso_solicitud       INTEGER REFERENCES solicitud_paso_aprobacion (id_paso_solicitud) ON DELETE SET NULL,
    id_usuario              INTEGER NOT NULL REFERENCES usuario (id_usuario),
    accion                  accion_solicitud NOT NULL,
    estado_anterior         estado_solicitud,
    estado_nuevo            estado_solicitud NOT NULL,
    comentario              VARCHAR(400),
    fecha_hora              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_historial_una_solicitud CHECK (
        (id_solicitud_permiso IS NOT NULL AND id_solicitud_hora_extra IS NULL)
        OR (id_solicitud_permiso IS NULL AND id_solicitud_hora_extra IS NOT NULL)
    )
);

-- -----------------------------------------------------------------------------
-- Auditoría general (SS-07, RI-06, RG-14, RNF-S03)
-- -----------------------------------------------------------------------------
CREATE TABLE auditoria (
    id_auditoria    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario      INTEGER REFERENCES usuario (id_usuario),
    accion          VARCHAR(80) NOT NULL,
    entidad         VARCHAR(60) NOT NULL,
    id_entidad      INTEGER,
    detalle         JSONB,
    direccion_ip    VARCHAR(45),
    fecha_hora      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- -----------------------------------------------------------------------------
-- Carga masiva Excel (RI-08, INT-01, PNI-01)
-- -----------------------------------------------------------------------------
CREATE TABLE carga_masiva (
    id_carga            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario          INTEGER NOT NULL REFERENCES usuario (id_usuario),
    nombre_archivo      VARCHAR(255) NOT NULL,
    total_filas         INTEGER NOT NULL DEFAULT 0,
    filas_exitosas      INTEGER NOT NULL DEFAULT 0,
    filas_fallidas      INTEGER NOT NULL DEFAULT 0,
    estado              estado_carga NOT NULL DEFAULT 'PROCESANDO',
    mensaje             VARCHAR(400),
    fecha_inicio        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_fin           TIMESTAMPTZ,
    CONSTRAINT ck_carga_totales CHECK (
        total_filas >= 0
        AND filas_exitosas >= 0
        AND filas_fallidas >= 0
        AND filas_exitosas + filas_fallidas <= total_filas
    )
);

CREATE TABLE carga_masiva_detalle (
    id_detalle      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carga        INTEGER NOT NULL REFERENCES carga_masiva (id_carga) ON DELETE CASCADE,
    numero_fila     INTEGER NOT NULL,
    resultado       resultado_fila_carga NOT NULL,
    id_empleado     INTEGER REFERENCES empleado (id_empleado),
    mensaje         VARCHAR(400),
    datos           JSONB,
    CONSTRAINT uq_carga_fila UNIQUE (id_carga, numero_fila)
);

