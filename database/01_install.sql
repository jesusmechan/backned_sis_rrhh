CREATE OR REPLACE FUNCTION fn_resolver_configuracion(
    p_tipo_origen tipo_origen_flujo,
    p_id_tipo_permiso INTEGER DEFAULT NULL
)
RETURNS INTEGER AS $$
DECLARE
    v_id INTEGER;
BEGIN
    IF p_tipo_origen = 'PERMISO' AND p_id_tipo_permiso IS NOT NULL THEN
        SELECT id_configuracion INTO v_id
        FROM configuracion_aprobacion
        WHERE activo
          AND tipo_origen = 'PERMISO'
          AND id_tipo_permiso = p_id_tipo_permiso
        LIMIT 1;
    END IF;

    IF v_id IS NULL THEN
        SELECT id_configuracion INTO v_id
        FROM configuracion_aprobacion
        WHERE activo
          AND tipo_origen = p_tipo_origen
          AND id_tipo_permiso IS NULL
        LIMIT 1;
    END IF;

    IF v_id IS NULL THEN
        RAISE EXCEPTION 'No existe una configuración de aprobación activa para %.', p_tipo_origen;
    END IF;

    RETURN v_id;
END;
$$ LANGUAGE plpgsql STABLE;

CREATE OR REPLACE FUNCTION fn_resolver_aprobador(
    p_tipo_aprobador tipo_aprobador,
    p_id_rol INTEGER,
    p_id_usuario INTEGER,
    p_id_empleado INTEGER
)
RETURNS INTEGER AS $$
DECLARE
    v_id_usuario INTEGER;
BEGIN
    IF p_tipo_aprobador = 'USUARIO' THEN
        SELECT id_usuario INTO v_id_usuario
        FROM usuario
        WHERE id_usuario = p_id_usuario
          AND activo;
    ELSIF p_tipo_aprobador = 'JEFE_INMEDIATO' THEN
        SELECT u.id_usuario INTO v_id_usuario
        FROM empleado e
        JOIN usuario u ON u.id_empleado = e.id_jefe_inmediato
        WHERE e.id_empleado = p_id_empleado
          AND u.activo;
    ELSIF p_tipo_aprobador = 'ROL' THEN
        v_id_usuario := NULL;
    END IF;

    RETURN v_id_usuario;
END;
$$ LANGUAGE plpgsql STABLE;

