CREATE OR REPLACE FUNCTION fn_validar_hora_extra()
RETURNS TRIGGER AS $$
DECLARE
    v_max_diarias NUMERIC;
    v_max_semanales NUMERIC;
    v_acumulado_dia NUMERIC;
    v_acumulado_semana NUMERIC;
BEGIN
    SELECT valor::NUMERIC INTO v_max_diarias
    FROM parametro_sistema WHERE clave = 'max_horas_extras_diarias';

    SELECT valor::NUMERIC INTO v_max_semanales
    FROM parametro_sistema WHERE clave = 'max_horas_extras_semanales';

    SELECT COALESCE(SUM(cantidad_horas), 0) INTO v_acumulado_dia
    FROM solicitud_hora_extra
    WHERE id_empleado = NEW.id_empleado
      AND fecha = NEW.fecha
      AND estado IN ('PENDIENTE', 'APROBADO')
      AND (TG_OP = 'INSERT' OR id_solicitud_hora_extra <> NEW.id_solicitud_hora_extra);

    IF v_acumulado_dia + NEW.cantidad_horas > COALESCE(v_max_diarias, 4) THEN
        RAISE EXCEPTION 'La cantidad de horas extras del día supera el máximo permitido (%).',
            COALESCE(v_max_diarias, 4);
    END IF;

    SELECT COALESCE(SUM(cantidad_horas), 0) INTO v_acumulado_semana
    FROM solicitud_hora_extra
    WHERE id_empleado = NEW.id_empleado
      AND fecha >= date_trunc('week', NEW.fecha)::date
      AND fecha < date_trunc('week', NEW.fecha)::date + 7
      AND estado IN ('PENDIENTE', 'APROBADO')
      AND (TG_OP = 'INSERT' OR id_solicitud_hora_extra <> NEW.id_solicitud_hora_extra);

    IF v_acumulado_semana + NEW.cantidad_horas > COALESCE(v_max_semanales, 12) THEN
        RAISE EXCEPTION 'La cantidad de horas extras de la semana supera el máximo permitido (%).',
            COALESCE(v_max_semanales, 12);
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validar_hora_extra
    BEFORE INSERT OR UPDATE OF cantidad_horas, fecha, estado ON solicitud_hora_extra
    FOR EACH ROW
    WHEN (NEW.estado IN ('PENDIENTE', 'APROBADO'))
    EXECUTE FUNCTION fn_validar_hora_extra();

