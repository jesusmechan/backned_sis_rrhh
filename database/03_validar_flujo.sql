    v_pendientes INTEGER;
    v_fallos INTEGER;
BEGIN
    SELECT COUNT(*) INTO v_pendientes
    FROM v_bandeja_aprobacion
    WHERE motivo LIKE '[VAL-MANUAL]%';

    PERFORM fn_val_registrar(
        'BANDEJA-MANUAL',
        v_pendientes >= 4,
        format('casos manuales en bandeja=%s', v_pendientes)
    );

    SELECT COUNT(*) INTO v_fallos
    FROM validacion_flujo_resultado
    WHERE NOT ok;

    IF v_fallos > 0 THEN
        RAISE EXCEPTION 'La validación del flujo falló en % caso(s). Revisa validacion_flujo_resultado.', v_fallos;
    END IF;
END;
$$;

