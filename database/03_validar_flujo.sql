DROP TABLE IF EXISTS validacion_flujo_resultado;

CREATE TABLE validacion_flujo_resultado (
    id_resultado    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caso            VARCHAR(80) NOT NULL,
    detalle         VARCHAR(400),
    ok              BOOLEAN NOT NULL,
    fecha           TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE OR REPLACE FUNCTION fn_val_registrar(p_caso TEXT, p_ok BOOLEAN, p_detalle TEXT)
RETURNS VOID AS $$
BEGIN
    INSERT INTO validacion_flujo_resultado (caso, detalle, ok)
    VALUES (p_caso, p_detalle, p_ok);

    RAISE NOTICE '% % — %',
        CASE WHEN p_ok THEN 'OK   ' ELSE 'FALLO' END,
        p_caso,
        COALESCE(p_detalle, '');
END;
$$ LANGUAGE plpgsql;

