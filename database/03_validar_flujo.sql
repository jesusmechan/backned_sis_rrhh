-- Caso 1: vacaciones instancia 3 pasos (jefe -> RR. HH. -> Gerencia)
-- -----------------------------------------------------------------------------
DO $$
DECLARE
    v_id INTEGER;
    v_pasos INTEGER;
    v_flujo TEXT;
    v_asignado TEXT;
    v_estado TEXT;
BEGIN
    INSERT INTO solicitud_permiso (id_empleado, id_tipo_permiso, fecha_inicio, fecha_fin, motivo)
    VALUES (
        (SELECT id_empleado FROM empleado WHERE codigo_empleado = 'AND-011'),
        (SELECT id_tipo_permiso FROM tipo_permiso WHERE codigo = 'VACACIONES'),
        '2026-12-01', '2026-12-15',
        '[VAL-AUTO] Vacaciones de Diego León — flujo de 3 pasos'
    )
    RETURNING id_solicitud_permiso INTO v_id;

    SELECT cfg.codigo, COUNT(*)
    INTO v_flujo, v_pasos
    FROM solicitud_permiso sp
    JOIN configuracion_aprobacion cfg ON cfg.id_configuracion = sp.id_configuracion
    JOIN solicitud_paso_aprobacion p ON p.id_solicitud_permiso = sp.id_solicitud_permiso
    WHERE sp.id_solicitud_permiso = v_id
    GROUP BY cfg.codigo;

    PERFORM fn_val_registrar(
        'VACACIONES-INSTANCIA',
        v_flujo = 'CFG-PERMISO-VACACIONES' AND v_pasos = 3,
        format('flujo=%s pasos=%s', v_flujo, v_pasos)
    );

    SELECT u.nombre_usuario, p.estado::TEXT
    INTO v_asignado, v_estado
    FROM solicitud_paso_aprobacion p
    JOIN usuario u ON u.id_usuario = p.id_usuario_asignado
    WHERE p.id_solicitud_permiso = v_id
      AND p.numero_paso = 1;

    PERFORM fn_val_registrar(
        'VACACIONES-PASO1-JEFE',
        v_asignado = 'cmendoza' AND v_estado = 'EN_CURSO',
        format('asignado=%s estado=%s', v_asignado, v_estado)
    );
END;
$$;

