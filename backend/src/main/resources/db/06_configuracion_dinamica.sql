CREATE TABLE IF NOT EXISTS afp (
    codigo          VARCHAR(20) PRIMARY KEY,
    nombre          VARCHAR(80) NOT NULL,
    tasa_comision   NUMERIC(7, 5) NOT NULL,
    orden           INTEGER NOT NULL DEFAULT 0,
    activo          BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_afp_tasa CHECK (tasa_comision >= 0 AND tasa_comision < 1)
);

INSERT INTO afp (codigo, nombre, tasa_comision, orden)
SELECT v.codigo, v.nombre,
       COALESCE((SELECT p.valor::NUMERIC FROM parametro_sistema p WHERE p.clave = v.clave), v.tasa),
       v.orden
FROM (VALUES
    ('HABITAT', 'AFP Habitat', 'tasa_afp_comision_habitat', 0.0147, 10),
    ('INTEGRA', 'AFP Integra', 'tasa_afp_comision_integra', 0.0155, 20),
    ('PRIMA', 'AFP Prima', 'tasa_afp_comision_prima', 0.0160, 30),
    ('PROFUTURO', 'AFP Profuturo', 'tasa_afp_comision_profuturo', 0.0169, 40)
) AS v(codigo, nombre, clave, tasa, orden)
ON CONFLICT (codigo) DO NOTHING;

