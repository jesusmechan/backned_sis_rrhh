-- 4. Régimen laboral como tabla (factores de beneficios)
-- -----------------------------------------------------------------------------
ALTER TABLE contrato ADD COLUMN IF NOT EXISTS regimen_laboral VARCHAR(20) NOT NULL DEFAULT 'GENERAL';

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_type WHERE typname = 'regimen_laboral' AND typtype = 'e') THEN
        ALTER TABLE contrato ALTER COLUMN regimen_laboral DROP DEFAULT;
        ALTER TABLE contrato ALTER COLUMN regimen_laboral TYPE VARCHAR(20) USING regimen_laboral::TEXT;
        ALTER TABLE contrato ALTER COLUMN regimen_laboral SET DEFAULT 'GENERAL';
